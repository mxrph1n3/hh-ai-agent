from config import STUDIO_SUMMARY, YANDEX_TIMELINE
from ai.analyzer import _ask_ollama

_PLAN_MARKERS = (
    "план прилага",
    "план приложен",
    "приложен план",
    "прикреплен план",
    "есть план",
    "есть планировк",
    "обмерный план",
    "чертеж приложен",
    "чертежи приложен",
    "во вложении план",
    "план во вложении",
    "планировка во вложении",
)


def _order_has_plan(description: str) -> bool:
    text = description.lower().replace("ё", "е")
    return any(marker in text for marker in _PLAN_MARKERS)


def build_reply(title: str, description: str) -> str:
    """Короткий отклик студии. Заказчик не писал нам: он выбирает исполнителя."""
    task = " ".join(title.split()).strip().rstrip(".")
    if _order_has_plan(description):
        closing = (
            "План в заказе видим. Посмотрим его и подскажем, какой из двух вариантов подойдёт."
        )
    else:
        closing = (
            "Направьте план помещения. Посмотрим задачу и подскажем, какой из двух вариантов подойдёт."
        )
    return (
        f"Здравствуйте. Мы дизайн-студия интерьера и готовы взять ваш заказ: {task}.\n\n"
        "Можем оперативно выехать на замер. Предлагаем два формата. "
        "Базовый пакет: планировка до 2 вариантов, планы монтажа и демонтажа, "
        "чертежи электрики, схема полов, план потолков, коллажи и список материалов. "
        "Полный дизайн-проект: планировка до 3 вариантов, развёртки стен, "
        "раскладка плитки, схема дверей и 3D-визуализация.\n\n"
        f"Срок: {YANDEX_TIMELINE}.\n\n"
        f"{closing}"
    )


async def is_order_suitable(title: str, description: str) -> bool:
    """Сомнение и сбой модели считаются отказом: откликов в день мало."""
    prompt = f"""оцени заказ для дизайн-студии интерьера. ответь одним словом: YES или NO.

студия:
{STUDIO_SUMMARY}

YES если заказ хоть как-то связан с ремонтом или интерьером помещения:
- ремонт квартиры, дома, комнаты, кухни, санузла, под ключ, черновая и чистовая отделка
- перепланировка, демонтаж, стяжка, штукатурка, плитка, потолки, полы, окна внутри ремонта
- сантехника и электрика, если это часть ремонта помещения, а не разовая починка техники
- дизайн интерьера, дизайн-проект, планировка, 3d, комплектация, авторский надзор

NO только если заказ вообще не про ремонт и не про интерьер:
- клининг, химчистка, авто, красота, юрист, репетитор, курьер, грузоперевозки
- починить кран, розетку или стиральную машину без ремонта помещения
- сотрудничество, бартер, бесплатно, за отзыв, за упоминание, обмен услугами, партнёрство без оплаты

если в тексте есть «сотрудничество» или бартер — сразу NO, даже если рядом ремонт или дизайн.
если заказ про ремонт или отделку за деньги и есть сомнение — YES

заказ: {title}
описание: {description[:3500]}

ответ одним словом: YES или NO
"""
    try:
        answer = await _ask_ollama(prompt, "отвечай только YES или NO.")
    except Exception as e:
        print(f"   Ollama недоступна, заказ пропускаем: {e}")
        return False

    first = answer.upper().split()[0] if answer else ""
    if first.startswith("YES"):
        return True
    print(f"   ИИ: NO — {answer[:160]}")
    return False


async def generate_reply(title: str, description: str) -> str:
    """Фиксированный короткий отклик. Модель текст не пишет."""
    return build_reply(title, description)
