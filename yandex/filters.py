import re

# Если в названии есть ремонт или дизайн, чужие услуги не отсекаем.
ALLOW = [
    "ремонт",
    "отделк",
    "дизайн",
    "интерьер",
    "планиров",
    "перепланир",
    "визуализ",
    "комплектац",
    "авторск",
    "квартир",
    "чернов",
    "чистов",
    "стяжк",
    "штукатур",
    "плитк",
    "демонтаж",
    "потолок",
    "потолк",
    "санузел",
    "ванн",
    "под ключ",
]

# Чужие услуги. Не применяются, если текст уже про ремонт или дизайн.
REJECT = [
    "клининг",
    "уборк",
    "химчист",
    "маникюр",
    "педикюр",
    "парикмах",
    "юрист",
    "репетитор",
    "грузоперевоз",
    "курьер",
    "вскрытие",
    "эвакуатор",
    "шиномонтаж",
    "дезинсек",
]

# Бартер и сотрудничество отклоняем даже в ремонтном заказе.
UNPAID = [
    "сотруднич",
    "бартер",
    "взаимопиар",
    "за отзыв",
    "обмен услуг",
    "партнерств",
    "партнёрств",
]

# «авто» отдельно, чтобы не отсечь «авторский надзор».
_AUTO = re.compile(r"(?<![\w])авто(?!р)", re.IGNORECASE)


def reject_reason(text: str) -> str | None:
    """Стоп-слово. Сотрудничество и бартер важнее ремонта и дизайна."""
    lowered = text.lower().replace("ё", "е")
    for word in UNPAID:
        if word.replace("ё", "е") in lowered:
            return word
    if any(word in lowered for word in ALLOW):
        return None
    if _AUTO.search(lowered):
        return "авто"
    for word in REJECT:
        if word in lowered:
            return word
    return None
