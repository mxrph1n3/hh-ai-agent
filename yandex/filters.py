import re

# Стволы слов: заказ с таким названием сразу мимо, без Ollama.
REJECT = [
    "сантех",
    "электрик",
    "электромонтаж",
    "окна",
    "окон",
    "кондиционер",
    "клининг",
    "уборк",
    "химчист",
    "сборк",
    "маникюр",
    "педикюр",
    "парикмах",
    "юрист",
    "репетитор",
    "грузоперевоз",
    "курьер",
    "вскрытие",
    "замк",
    "эвакуатор",
    "шиномонтаж",
    "дезинсек",
]

# «авто» отдельно, чтобы не отсечь «авторский надзор».
_AUTO = re.compile(r"(?<![\w])авто(?!р)", re.IGNORECASE)


def reject_reason(title: str) -> str | None:
    """Стоп-слово в названии заказа. None — можно смотреть дальше."""
    text = title.lower()
    if _AUTO.search(text):
        return "авто"
    for word in REJECT:
        if word in text:
            return word
    return None
